class OnboardingError(Exception):
    pass


class OnboardingService:
    """Step 31: create/configure a business without manual SQL from the operator."""

    def __init__(self, conn):
        self.conn = conn

    def _columns(self, table: str) -> dict[str, dict[str, Any]]:
        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT column_name, data_type, is_nullable, column_default
                FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = %s
                ORDER BY ordinal_position
                """,
                (table,),
            )
            rows = cur.fetchall()
        if not rows:
            raise OnboardingError(f"La tabla public.{table} no existe.")
        return {
            r[0]: {
                "data_type": r[1],
                "is_nullable": r[2] == "YES",
                "default": r[3],
            }
            for r in rows
        }

    @staticmethod
    def _safe_json(value: Any) -> Any:
        if isinstance(value, dict):
            return {str(k): OnboardingService._safe_json(v) for k, v in value.items()}
        if isinstance(value, list):
            return [OnboardingService._safe_json(v) for v in value]
        if isinstance(value, (datetime,)):
            return value.isoformat()
        if isinstance(value, Decimal):
            return float(value)
        if isinstance(value, UUID):
            return str(value)
        return value

    def _insert(self, table: str, values: dict[str, Any], *, returning: str = "id") -> Any:
        cols = self._columns(table)
        unknown = sorted(set(values) - set(cols))
        if unknown:
            values = {k: v for k, v in values.items() if k in cols}

        # Convert dict/list values to JSONB only when target is JSON/JSONB.
        normalized = {}
        for key, value in values.items():
            meta = cols[key]
            if value is not None and meta["data_type"] in {"json", "jsonb"} and isinstance(value, (dict, list)):
                normalized[key] = Jsonb(value)
            else:
                normalized[key] = value

        if not normalized:
            raise OnboardingError(f"No hay columnas utilizables para insertar en {table}.")

        missing_required = [
            name for name, meta in cols.items()
            if meta["is_nullable"] is False
            and meta["default"] is None
            and name not in normalized
        ]
        # IDs/timestamps may be generated by application only when no DB default exists.
        if "id" in missing_required:
            normalized["id"] = uuid4()
            missing_required.remove("id")
        if missing_required:
            raise OnboardingError(
                f"La tabla {table} exige columnas sin valor por defecto que el onboarding no conoce: {missing_required}"
            )

        names = list(normalized.keys())
        placeholders = [sql.Placeholder(name) for name in names]
        query = sql.SQL("INSERT INTO {} ({}) VALUES ({}) RETURNING {}") .format(
            sql.Identifier(table),
            sql.SQL(", ").join(sql.Identifier(n) for n in names),
            sql.SQL(", ").join(placeholders),
            sql.Identifier(returning),
        )
        with self.conn.cursor() as cur:
            cur.execute(query, normalized)
            return cur.fetchone()[0]

    def _fetch_business(self, business_id: UUID) -> dict[str, Any] | None:
        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT b.id, b.name, b.business_type, b.timezone, b.currency, b.status,
                       bp.industry, bp.short_description, bp.operating_hours,
                       bp.policies, bp.objectives, bp.autonomy_config, bp.status
                FROM businesses b
                LEFT JOIN business_profiles bp
                  ON bp.business_id = b.id AND bp.status = 'active'
                WHERE b.id = %s
                ORDER BY bp.created_at DESC NULLS LAST
                LIMIT 1
                """,
                (business_id,),
            )
            row = cur.fetchone()
        if not row:
            return None
        return {
            "id": row[0], "name": row[1], "business_type": row[2],
            "timezone": row[3], "currency": row[4], "status": row[5],
            "profile": {
                "industry": row[6], "short_description": row[7],
                "operating_hours": row[8], "policies": row[9],
                "objectives": row[10], "autonomy_config": row[11],
                "status": row[12],
            },
        }

    def _ensure_default_permissions(self, business_id: UUID) -> None:
        """Ensure a newly onboarded tenant has the safe baseline Galaxy permissions.

        The operation is idempotent so it can also repair an existing tenant created
        by an earlier Step 31 build without creating duplicate permissions.
        """
        definitions = [
            {
                "name": "Galaxy read business profile",
                "description": "Galaxy can read the business profile.",
                "resource_type": "business_profile",
                "action_type": "read",
                "effect": "allow",
                "requires_approval": False,
                "priority": 100,
            },
            {
                "name": "Galaxy read customer",
                "description": "Galaxy can read customer information.",
                "resource_type": "customer",
                "action_type": "read",
                "effect": "allow",
                "requires_approval": False,
                "priority": 100,
            },
            {
                "name": "Galaxy read product",
                "description": "Galaxy can read product information.",
                "resource_type": "product",
                "action_type": "read",
                "effect": "allow",
                "requires_approval": False,
                "priority": 100,
            },
            {
                "name": "Galaxy read inventory",
                "description": "Galaxy can read inventory information.",
                "resource_type": "inventory",
                "action_type": "read",
                "effect": "allow",
                "requires_approval": False,
                "priority": 100,
            },
            {
                "name": "Galaxy read order",
                "description": "Galaxy can read order information.",
                "resource_type": "order",
                "action_type": "read",
                "effect": "allow",
                "requires_approval": False,
                "priority": 100,
            },
            {
                "name": "Galaxy create order with approval",
                "description": "Galaxy may prepare an order, but a human must approve it before execution.",
                "resource_type": "order",
                "action_type": "create",
                "effect": "allow",
                "requires_approval": True,
                "priority": 100,
            },
            {
                "name": "Block autonomous inventory update",
                "description": "Inventory updates remain blocked until the approval/execution workflow is fully implemented.",
                "resource_type": "inventory",
                "action_type": "update",
                "effect": "deny",
                "requires_approval": False,
                "priority": 10,
            },
        ]

        with self.conn.cursor() as cur:
            for item in definitions:
                cur.execute(
                    """
                    SELECT id
                    FROM permissions
                    WHERE business_id = %s
                      AND subject_type = 'system'
                      AND resource_type = %s
                      AND action_type = %s
                      AND effect = %s
                      AND enabled = TRUE
                    LIMIT 1
                    """,
                    (business_id, item["resource_type"], item["action_type"], item["effect"]),
                )
                if cur.fetchone():
                    continue
                self._insert(
                    "permissions",
                    {
                        "business_id": business_id,
                        "name": item["name"],
                        "description": item["description"],
                        "subject_type": "system",
                        "resource_type": item["resource_type"],
                        "action_type": item["action_type"],
                        "effect": item["effect"],
                        "requires_approval": item["requires_approval"],
                        "priority": item["priority"],
                        "enabled": True,
                    },
                )

    def repair_permissions(self, business_id: UUID) -> dict[str, Any]:
        """Repair the baseline system permissions for an existing tenant."""
        if not self._fetch_business(business_id):
            self.conn.rollback()
            raise OnboardingError("Business not found")
        try:
            self._ensure_default_permissions(business_id)
            self.conn.commit()
        except Exception:
            self.conn.rollback()
            raise
        return {"success": True, "business_id": business_id, "message": "Default Galaxy permissions are ready."}

    def provision_new_tenant(self, business_id: UUID, business_name: str, business_type: str) -> dict[str, Any]:
        """
        Paso 92: Provisiona un tenant con perfiles, políticas y capacidades por defecto.
        Evita tener que configurar manualmente la IA para cada cliente nuevo.
        """
        with self.conn.cursor() as cur:
            # 1. Crear el Blueprint (Cerebro Base) por defecto para este negocio
            # CAMBIO APLICADO: Usamos 'agent_name' en lugar de 'name'
            blueprint_id = str(uuid4())
            cur.execute("""
                INSERT INTO agent_blueprints (id, business_id, agent_name, core_objective, capabilities)
                VALUES (%s, %s, %s, %s, %s::jsonb)
            """, (
                blueprint_id, 
                str(business_id), 
                f"Autopilot - {business_name}", 
                "Atender clientes, gestionar inventario y maximizar conversión de ventas.", 
                '["sales", "support", "inventory"]'
            ))

            # 2. Inyectar Política de Gobernanza Básica (Seguridad por defecto)
            policy_id = str(uuid4())
            cur.execute("""
                INSERT INTO autonomy_policies (id, business_id, action_name, policy_mode, value_limit)
                VALUES (%s, %s, 'issue_refund', 'requires_human', 0.00)
            """, (policy_id, str(business_id)))

            # 3. Configurar su primera Meta de Negocio (Goal)
            goal_id = str(uuid4())
            cur.execute("""
                INSERT INTO business_goals (id, business_id, name, metric_name, target_value)
                VALUES (%s, %s, 'Aumentar Conversión Inicial', 'conversion_rate', 5.0)
            """, (goal_id, str(business_id)))

            # 4. Dejar constancia inmutable en la auditoría
            AuditService(self.conn).log_action(
                business_id, "SYSTEM_ONBOARDING", "TENANT_PROVISIONED", str(business_id),
                {"business_type": business_type, "status": "ready"}
            )

            return {
                "status": "provisioned",
                "business_id": str(business_id),
                "blueprint_id": blueprint_id,
                "message": "Cerebro IA, Políticas y Metas inicializadas exitosamente."
            }

    def create_business(self, payload: dict[str, Any]) -> dict[str, Any]:
        name = str(payload.get("name", "")).strip()
        if not name:
            raise OnboardingError("El nombre del negocio es obligatorio.")

        business_type = str(payload.get("business_type") or "Retail").strip()
        timezone = str(payload.get("timezone") or "America/New_York").strip()
        currency = str(payload.get("currency") or "USD").strip().upper()
        industry = str(payload.get("industry") or business_type).strip()
        description = str(payload.get("description") or "").strip()
        legal_name = str(payload.get("legal_name") or name).strip()
        country = str(payload.get("country") or "United States").strip()

        hours = payload.get("operating_hours") or {
            "monday": {"open": "09:00", "close": "19:00"},
            "tuesday": {"open": "09:00", "close": "19:00"},
            "wednesday": {"open": "09:00", "close": "19:00"},
            "thursday": {"open": "09:00", "close": "19:00"},
            "friday": {"open": "09:00", "close": "19:00"},
            "saturday": {"open": "09:00", "close": "17:00"},
            "sunday": {"closed": True},
        }
        policies = payload.get("policies") or {
            "max_auto_discount_percent": 5,
            "price_changes_require_approval": True,
            "refunds_require_approval": True,
            "supplier_purchases_require_approval": True,
            "high_risk_requires_approval": True,
        }
        objectives = payload.get("objectives") or [
            "Aumentar ventas",
            "Reducir faltantes de inventario",
            "Mejorar tiempo de respuesta",
        ]
        autonomy = payload.get("autonomy_config") or {
            "level": "L1",
            "default_level": "L1",
            "max_auto_discount_percent": 5,
            "max_inventory_adjustment": 2,
            "supplier_auto_purchases": False,
            "high_risk_approval_required": True,
        }
        communication = payload.get("communication_config") or {
            "preferred_channel": "webchat",
            "tone": "professional-friendly",
            "handoff_enabled": True,
        }

        self.conn.autocommit = False
        try:
            business_id = self._insert(
                "businesses",
                {
                    "id": uuid4(),
                    "name": name,
                    "legal_name": legal_name,
                    "business_type": business_type,
                    "description": description or None,
                    "phone": payload.get("phone") or None,
                    "email": payload.get("email") or None,
                    "website": payload.get("website") or None,
                    "timezone": timezone,
                    "currency": currency,
                    "status": "active",
                },
            )

            profile_id = self._insert(
                "business_profiles",
                {
                    "id": uuid4(),
                    "business_id": business_id,
                    "industry": industry,
                    "short_description": description or f"{business_type} - {name}",
                    "legal_name": legal_name,
                    "address": payload.get("address") or None,
                    "city": payload.get("city") or None,
                    "state_province": payload.get("state_province") or None,
                    "country": country,
                    "postal_code": payload.get("postal_code") or None,
                    "operating_hours": hours,
                    "policies": policies,
                    "processes": payload.get("processes") or {},
                    "objectives": objectives,
                    "autonomy_config": autonomy,
                    "communication_config": communication,
                    "social_links": payload.get("social_links") or {},
                    "additional_settings": payload.get("additional_settings") or {},
                    "profile_version": 1,
                    "status": "active",
                },
            )

            product_payload = payload.get("product") or None
            product_id = None
            inventory_id = None
            customer_id = None

            if product_payload and str(product_payload.get("name", "")).strip():
                product_name = str(product_payload["name"]).strip()
                price = float(product_payload.get("price") or 0)
                if price < 0:
                    raise OnboardingError("El precio no puede ser negativo.")
                product_id = self._insert(
                    "products",
                    {
                        "id": uuid4(),
                        "business_id": business_id,
                        "name": product_name,
                        "description": str(product_payload.get("description") or "").strip() or None,
                        "sku": str(product_payload.get("sku") or "").strip() or None,
                        "category": str(product_payload.get("category") or "General").strip(),
                        "price": price,
                        "currency": currency,
                        "status": "active",
                        "is_active": True,
                    },
                )
                inventory_id = self._insert(
                    "inventory",
                    {
                        "id": uuid4(),
                        "business_id": business_id,
                        "product_id": product_id,
                        "quantity": float(product_payload.get("quantity") or 0),
                        "minimum_quantity": float(product_payload.get("minimum_quantity") or 0),
                        "location": str(product_payload.get("location") or "main").strip(),
                        "last_count_method": "onboarding",
                    },
                )

            customer_payload = payload.get("customer") or None
            if customer_payload and str(customer_payload.get("full_name", "")).strip():
                customer_id = self._insert(
                    "customers",
                    {
                        "id": uuid4(),
                        "business_id": business_id,
                        "full_name": str(customer_payload["full_name"]).strip(),
                        "email": str(customer_payload.get("email") or "").strip() or None,
                        "phone": str(customer_payload.get("phone") or "").strip() or None,
                        "status": "active",
                        "source": "onboarding",
                        "notes": "Cliente de prueba creado durante Step 31.",
                    },
                )

            self._ensure_default_permissions(business_id)

            owner_payload = payload.get("owner") or None
            owner_result = None
            if owner_payload:
                owner_email = str(owner_payload.get("email") or "").strip().lower()
                owner_name = str(owner_payload.get("full_name") or "").strip()
                owner_password = str(owner_payload.get("password") or "")
                owner_phone = str(owner_payload.get("phone") or "").strip() or None

                if not owner_email:
                    raise OnboardingError("El correo del OWNER es obligatorio.")
                if not owner_name:
                    raise OnboardingError("El nombre completo del OWNER es obligatorio.")
                if len(owner_password) < 8:
                    raise OnboardingError("La contraseña del OWNER debe tener al menos 8 caracteres.")

                with self.conn.cursor() as cur:
                    cur.execute(
                        "SELECT id, business_id FROM users WHERE LOWER(email) = %s LIMIT 1",
                        (owner_email,),
                    )
                    existing_owner = cur.fetchone()
                    if existing_owner is not None:
                        raise OnboardingError(
                            f"El correo del OWNER ya está registrado en Galaxy "
                            f"(business_id={existing_owner[1]}). Usa otro correo."
                        )

                    owner_id = uuid4()
                    owner_hash = get_password_hash(owner_password)
                    cur.execute(
                        """
                        INSERT INTO users (
                            id, business_id, email, password_hash, role, full_name, phone, status
                        )
                        VALUES (%s, %s, %s, %s, 'OWNER', %s, %s, 'active')
                        """,
                        (
                            owner_id,
                            business_id,
                            owner_email,
                            owner_hash,
                            owner_name,
                            owner_phone,
                        ),
                    )
                owner_result = {
                    "user_id": owner_id,
                    "business_id": business_id,
                    "email": owner_email,
                    "role": "OWNER",
                    "full_name": owner_name,
                }

            self.conn.commit()
        except Exception:
            self.conn.rollback()
            raise

        return {
            "success": True,
            "business_id": business_id,
            "business_profile_id": profile_id,
            "product_id": product_id,
            "inventory_id": inventory_id,
            "customer_id": customer_id,
            "owner": self._safe_json(owner_result),
            "business": self._fetch_business(business_id),
        }

    def summary(self, business_id: UUID) -> dict[str, Any]:
        business = self._fetch_business(business_id)
        if not business:
            raise OnboardingError("Business not found")
        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT id, name, price, category, sku, status
                FROM products
                WHERE business_id = %s
                ORDER BY created_at DESC
                LIMIT 20
                """,
                (business_id,),
            )
            products = [dict(zip(["id", "name", "price", "category", "sku", "status"], r)) for r in cur.fetchall()]

            cur.execute(
                """
                SELECT i.id, i.product_id, p.name, i.quantity, i.minimum_quantity, i.location
                FROM inventory i
                JOIN products p ON p.id = i.product_id AND p.business_id = i.business_id
                WHERE i.business_id = %s
                ORDER BY i.id DESC
                LIMIT 20
                """,
                (business_id,),
            )
            inventory = [dict(zip(["id", "product_id", "product_name", "quantity", "minimum_quantity", "location"], r)) for r in cur.fetchall()]

            cur.execute(
                """
                SELECT id, full_name, email, phone, status, source
                FROM customers
                WHERE business_id = %s
                ORDER BY created_at DESC
                LIMIT 20
                """,
                (business_id,),
            )
            customers = [dict(zip(["id", "full_name", "email", "phone", "status", "source"], r)) for r in cur.fetchall()]

        return {
            "success": True,
            "business": self._safe_json(business),
            "products": self._safe_json(products),
            "inventory": self._safe_json(inventory),
            "customers": self._safe_json(customers),
        }

    def list_businesses(self, limit: int = 50) -> list[dict[str, Any]]:
        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT id, name, business_type, timezone, currency, status, created_at
                FROM businesses
                ORDER BY created_at DESC
                LIMIT %s
                """,
                (limit,),
            )
            rows = cur.fetchall()
        keys = ["id", "name", "business_type", "timezone", "currency", "status", "created_at"]
        return self._safe_json([dict(zip(keys, row)) for row in rows])